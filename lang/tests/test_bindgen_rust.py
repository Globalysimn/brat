"""`brat bindgen` on Rust sources: `#[repr(C)]` in, working bindings out.

Rust is not installed in this sandbox, so the ABI is proved the only way it can
be proved here: the generated declarations are called against a C library with
the layout `#[repr(C)]` promises. If the mapping of a struct, a field, a pointer
or an enum were wrong, the values would not come back.

The output text is asserted literally, including what is refused: a struct
without `#[repr(C)]`, an enum with a payload, a `String` parameter. A generator
that silently guesses those is worse than one that skips them with a reason.
"""
import _cxx
import _scratch

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TMP = _scratch.mkdtemp(prefix="brat-rs-")

n = 0


def check(cond, msg):
    global n
    assert cond, msg
    n += 1


def write(name, text):
    path = os.path.join(TMP, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return path


RUST = '''// Surface a crate would export for C.
#[repr(C)]
pub struct Point {
    pub x: f64,
    pub y: f64,
}

#[repr(C)]
pub struct Rect {
    pub origin: Point,
    pub width: f64,
    pub height: f64,
}

#[repr(C)]
pub enum Kind {
    Circle = 0,
    Square = 1,
    Triangle = 3,
}

pub struct NotFfi {
    pub v: Vec<u8>,
}

#[no_mangle]
pub extern "C" fn make_rect(x: f64, y: f64, w: f64, h: f64) -> Rect {
    Rect { origin: Point { x, y }, width: w, height: h }
}

#[no_mangle]
pub extern "C" fn area(r: Rect) -> f64 {
    r.width * r.height
}

#[no_mangle]
pub extern "C" fn sum_rect(r: *const Rect) -> f64 {
    unsafe { (*r).origin.x + (*r).origin.y + (*r).width + (*r).height }
}

#[no_mangle]
pub extern "C" fn name_of(k: Kind) -> i32 {
    k as i32
}

#[no_mangle]
pub extern "C" fn not_ffi(s: String) -> i32 {
    s.len() as i32
}
'''

WANT = '''// generated by brat bindgen from geo.rs
extern struct Point { x: f64, y: f64 }
extern struct Rect { origin: Point, width: f64, height: f64 }

const Circle: i32 = 0
const Square: i32 = 1
const Triangle: i32 = 3

extern {
    extern fn make_rect(x: f64, y: f64, w: f64, h: f64) -> Rect;
    extern fn area(r: Rect) -> f64;
    extern fn sum_rect(r: ptr) -> f64;
    extern fn name_of(k: i32) -> i32;
}
// skipped NotFfi: not #[repr(C)]
// skipped not_ffi: parameter `String` has no C layout
'''

rust_path = write("geo.rs", RUST)
out_path = os.path.join(TMP, "geo.bri")
r = subprocess.run(_cxx.cli_args("bindgen", rust_path, "-o", out_path),
                   capture_output=True, text=True, timeout=120)
check(r.returncode == 0, "bindgen rc=%d %r" % (r.returncode, r.stdout + r.stderr))
check(r.stdout == "bindgen ok %s\n" % out_path, "bindgen stdout: %r" % r.stdout)
got = open(out_path, encoding="utf-8").read()
check(got == WANT, "generated text:\n--- got ---\n%s\n--- want ---\n%s" % (got, WANT))

# The ABI: a C library with the layout #[repr(C)] guarantees.
C = '''#include <stdint.h>
typedef struct { double x, y; } Point;
typedef struct { Point origin; double width, height; } Rect;

Rect make_rect(double x, double y, double w, double h) {
    Rect r; r.origin.x = x; r.origin.y = y; r.width = w; r.height = h;
    return r;
}
double area(Rect r) { return r.width * r.height; }
double sum_rect(const Rect *r) {
    return r->origin.x + r->origin.y + r->width + r->height;
}
int32_t name_of(int32_t k) { return k; }
'''
write("geo.c", C)
lib = os.path.join(TMP, "libgeo.so")
cc = subprocess.run(["cc", "-shared", "-fPIC", "-O2", os.path.join(TMP, "geo.c"),
                     "-o", lib], capture_output=True, text=True, timeout=120)
check(cc.returncode == 0, "cc: %r" % cc.stderr)

PROG = got.replace('extern {', 'extern "%s" {' % lib) + '''
fn main() -> i64 {
  let r = make_rect(1.0, 2.0, 3.0, 4.0)
  print(r.width)
  print(r.origin.y)
  print(area(r))
  print(name_of(Triangle))
  return 0
}
'''
path = write("use.brat", PROG)

interp = subprocess.run(_cxx.cli_args("run", "--interp", "--unsafe-ffi", path),
                        capture_output=True, text=True, timeout=300)
want_out = "3.0\n2.0\n12.0\n3\n"
check(interp.returncode == 0 and interp.stdout == want_out,
      "interp: rc=%d out=%r err=%r" % (interp.returncode, interp.stdout, interp.stderr))

exe = os.path.join(TMP, "use.exe")
built = subprocess.run(_cxx.cli_args("build", "--unsafe-ffi", path, "-o", exe),
                       capture_output=True, text=True, timeout=600)
check(built.returncode == 0, "build: %r" % (built.stdout + built.stderr))
native = subprocess.run([exe], capture_output=True, text=True, timeout=60)
check(native.returncode == 0 and native.stdout == want_out,
      "native: rc=%d out=%r err=%r" % (native.returncode, native.stdout, native.stderr))

# `-o` writes the file and prints one line; without it the text goes to stdout.
plain = subprocess.run(_cxx.cli_args("bindgen", rust_path),
                       capture_output=True, text=True, timeout=120)
check(plain.stdout == WANT, "stdout form: %r" % plain.stdout)

# The Python CLI is the fallback when the C++ binary is not built, and the one
# a fresh checkout starts with. It must write the same bytes; it used to die
# with a NameError on `ffi`, which the native binary hid from this file.
py_only = subprocess.run(_cxx.cli_args("bindgen", rust_path),
                         capture_output=True, text=True, timeout=120,
                         env=dict(os.environ, BRAT_NO_NATIVE_CLI="1"))
check(py_only.returncode == 0 and py_only.stdout == WANT,
      "python bindgen: rc=%d out=%r err=%r" % (py_only.returncode, py_only.stdout, py_only.stderr[-400:]))

# A file with no FFI surface is not an error: the block is empty and the
# skip comment says why.
empty = write("empty.rs", '''struct Inner { a: i32 }\n''')
r = subprocess.run(_cxx.cli_args("bindgen", empty), capture_output=True,
                   text=True, timeout=120)
check(r.returncode == 0 and "// skipped Inner: not #[repr(C)]" in r.stdout,
      "no surface: %r" % r.stdout)

# A top-level `const` is itself a regression: it emitted a file-scope Val that
# functions could not read, so `const Circle = 0` from bindgen was unusable in
# C even though the interpreter accepted it.
CONST = '''const N: i64 = 5
const M: f64 = 1.5

fn main() -> i64 {
  print(N)
  print(M)
  print(N * 2)
  return 0
}
'''
path = write("const.brat", CONST)
interp = subprocess.run(_cxx.cli_args("run", "--interp", path), capture_output=True,
                        text=True, timeout=300)
check(interp.returncode == 0 and interp.stdout == "5\n1.5\n10\n",
      "const interp: %r" % (interp.stdout + interp.stderr))
exe = os.path.join(TMP, "const.exe")
built = subprocess.run(_cxx.cli_args("build", "--unsafe-ffi", path, "-o", exe),
                       capture_output=True, text=True, timeout=600)
check(built.returncode == 0, "const build: %r" % (built.stdout + built.stderr))
native = subprocess.run([exe], capture_output=True, text=True, timeout=60)
check(native.returncode == 0 and native.stdout == interp.stdout,
      "const native: %r vs %r" % (native.stdout, interp.stdout))

print("BINDGEN RUST ALL GREEN (%d asserts)" % n)
